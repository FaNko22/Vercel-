-- يمنع تكرار نفس الرقم السري بين يوزرين (كان ممكن يحصل لو حد ضاف يوزرين
-- بنفس الرقم في نفس اللحظة من جهازين مختلفين، ووقتها تسجيل الدخول
-- بالرقم السري بس كان هيدخل دايمًا على نفس اليوزر الأول اللي اترقّم)
alter table app_users add constraint app_users_pin_unique unique (pin);

-- يمنع فتح شيفتين في نفس الوقت لنفس الفرع (لو حصل دبل كليك أو فتح من
-- جهازين مع بعض بالغلط، الشيفت التاني كان هيفضل مفتوح للأبد من غير ما
-- حد يلاحظه لأن الشاشة بتعرض شيفت واحد بس)
create unique index if not exists shifts_one_active_per_branch
  on shifts (branch_id) where (closed_at is null);
